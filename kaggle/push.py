def build_kernel_dir(stage: str, run_dir: Path, with_ckpt: bool) -> Path:
    kd = run_dir / "kernel"
    kd.mkdir(parents=True, exist_ok=True)
    files = {p: (ROOT / p).read_text(encoding="utf-8") for p in EMBED}
    meta = {"stage": stage, "init_from": INIT_FROM.get(stage), "budget_min": BUDGET_MIN[stage],
            "pushed_at": run_dir.name}
    script = ("# Auto-generated by kaggle/push.py - do not edit.\n"
              f"FILES_JSON = {json.dumps(json.dumps(files))}\n"
              f"META_JSON = {json.dumps(json.dumps(meta))}\n" + BOOTSTRAP)
    (kd / "runner_script.py").write_text(script, encoding="utf-8")
    km = {"id": KERNEL_REF, "title": KERNEL_TITLE, "code_file": "runner_script.py", "language": "python",
          "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
          "dataset_sources": [CKPT_REF] if with_ckpt else [], "kernel_sources": [], "competition_sources": []}
    (kd / "kernel-metadata.json").write_text(json.dumps(km, indent=2), encoding="utf-8")
    return kd


def poll(interval=60, timeout=46000) -> str:
    end = time.time() + timeout
    last = None
    while time.time() < end:
        try:
            raw = kaggle("kernels", "status", KERNEL_REF, timeout=120)
        except RuntimeError as e:
            raw = str(e)
        m = re.search(r'"(\w+)"', raw)
        state = (m.group(1) if m else raw).strip().lower()
        if state != last:
            print(f"[{dt.datetime.now():%H:%M:%S}] kernel status: {state}", flush=True)
            last = state
        if "complete" in state:
            return "complete"
        if "error" in state or "cancel" in state:
            return "error"
        time.sleep(interval)
    return "timeout"


def fetch(run_dir: Path) -> dict:
    out = run_dir / "output"
    out.mkdir(parents=True, exist_ok=True)
    for attempt in range(3):
        try:
            kaggle("kernels", "output", KERNEL_REF, "-p", str(out), timeout=3600)
            break
        except RuntimeError as e:
            print(f"output download attempt {attempt+1} failed: {str(e)[:300]}")
            time.sleep(30)
    result = {"output_dir": str(out)}
    log = out / f"{KERNEL_SLUG}.log"
    if log.exists():
        lines = log.read_text(encoding="utf-8", errors="replace").splitlines()
        result["log_tail"] = lines[-80:]
    st = out / "tv_status.json"
    result["job_status"] = json.loads(st.read_text())["status"] if st.exists() else "unknown"
    ckpts = list(out.glob("*/latest.pt"))
    result["checkpoints"] = [str(c) for c in ckpts]
    if ckpts and result["job_status"] == "ok":
        result["dataset"] = version_ckpt_dataset(out)
    return result


def version_ckpt_dataset(out: Path) -> str:
    """Push <stage>/latest.pt files as a new version of the private ckpt dataset (keeps other stages)."""
    stage_dirs = {c.parent.name: c for c in out.glob("*/latest.pt")}
    folder = RUNS / "_ckpt_dataset"
    if folder.exists():
        # keep previously fetched stages that this run didn't touch
        for old in folder.glob("*/latest.pt"):
            if old.parent.name not in stage_dirs:
                stage_dirs[old.parent.name] = old
    staging = RUNS / "_ckpt_staging"
    shutil.rmtree(staging, ignore_errors=True)
    for st, src in stage_dirs.items():
        (staging / st).mkdir(parents=True, exist_ok=True)
        shutil.copy(src, staging / st / "latest.pt")
    (staging / "dataset-metadata.json").write_text(json.dumps(
        {"title": CKPT_TITLE, "id": CKPT_REF, "licenses": [{"name": "CC0-1.0"}]}, indent=2))
    if dataset_exists():
        msg = kaggle("datasets", "version", "-p", str(staging), "-m", f"update {','.join(stage_dirs)}",
                     "--dir-mode", "zip", timeout=7200)
    else:
        msg = kaggle("datasets", "create", "-p", str(staging), "--dir-mode", "zip", timeout=7200)
    shutil.rmtree(folder, ignore_errors=True)
    shutil.move(str(staging), str(folder))
    print("[dataset]", msg.strip().splitlines()[-1])
    return msg.strip().splitlines()[-1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stage", nargs="?", choices=["smoke", "stage1", "stage2"])
    ap.add_argument("--no-wait", action="store_true")
    ap.add_argument("--status", action="store_true")
    ap.add_argument("--fetch", metavar="RUN_DIR")
    a = ap.parse_args()

    if a.status:
        print(kaggle("kernels", "status", KERNEL_REF, timeout=120).strip())
        return
    if a.fetch:
        print(json.dumps(fetch(Path(a.fetch)), indent=2))
        return
    if not a.stage:
        ap.error("stage required")

    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_dir = RUNS / f"{stamp}_{a.stage}"
    with_ckpt = dataset_exists()
    kd = build_kernel_dir(a.stage, run_dir, with_ckpt)
    print(f"pushing {a.stage} (ckpt dataset mounted: {with_ckpt}) from {kd}")
    push = kaggle("kernels", "push", "-p", str(kd), "--accelerator", "NvidiaTeslaT4", "-t", str(TIMEOUT_S[a.stage]),
                  timeout=600)
    summary = {"run_dir": str(run_dir), "stage": a.stage, "pushed_at": stamp, "push_output": push.strip(),
               "status": "pushed", "ckpt_mounted": with_ckpt}
    (run_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    print(push.strip())
    if a.no_wait:
        return
    summary["status"] = poll()
    if summary["status"] in ("complete", "error"):
        summary.update(fetch(run_dir))
    (run_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    print(json.dumps({k: v for k, v in summary.items() if k != "log_tail"}, indent=2))
    print("\n".join(summary.get("log_tail", [])[-40:]))


if __name__ == "__main__":
    main()
