"""
Local orchestrator: run one TernaVLM stage on a private Kaggle GPU kernel and bring the checkpoint home.

    python kaggle/push.py smoke                  # ~20 min, proves the pipeline
    python kaggle/push.py stage1                 # rerun each session until it prints "finished"
    python kaggle/push.py stage2
    python kaggle/push.py stage1 --no-wait       # just push, poll later with --status
    python kaggle/push.py --status               # print kernel status
    python kaggle/push.py --fetch <run_dir>      # download outputs for a pushed run and version the ckpt dataset

Design (mirrors Boulder_Vision_Platform's runner):
  * the whole repo (ternavlm/, train.py, configs/) is embedded into a single runner_script.py,
    so the kernel needs no GitHub access and stays private;
  * checkpoints persist in a private Kaggle dataset <user>/ternavlm-ckpt as <stage>/latest.pt,
    mounted read-only in the next kernel for --resume / --init;
  * every run gets runs/<UTC>_<stage>/{kernel,output,summary.json}.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
USER = "shivpratap0007"
KERNEL_SLUG = "ternavlm-runner"
KERNEL_TITLE = "TernaVLM Runner"
CKPT_SLUG = "ternavlm-ckpt"
CKPT_TITLE = "TernaVLM Checkpoints"
KERNEL_REF = f"{USER}/{KERNEL_SLUG}"
CKPT_REF = f"{USER}/{CKPT_SLUG}"
RUNS = ROOT / "runs"
EMBED = ["ternavlm/__init__.py", "ternavlm/ops.py", "ternavlm/ternary.py", "ternavlm/vlm.py", "ternavlm/data.py",
         "train.py", "requirements.txt", "configs/smoke.yaml", "configs/stage1.yaml", "configs/stage2.yaml"]
INIT_FROM = {"stage2": "stage1"}
TIMEOUT_S = {"smoke": 3600, "stage1": 43000, "stage2": 43000}
BUDGET_MIN = {"smoke": 40, "stage1": 680, "stage2": 680}


def kaggle(*args, timeout=3600) -> str:
    p = subprocess.run(["kaggle", *args], capture_output=True, text=True, encoding="utf-8", errors="replace",
                       timeout=timeout, env={**os.environ, "PYTHONUTF8": "1"})
    out = (p.stdout or "") + (p.stderr or "")
    if p.returncode != 0:
        raise RuntimeError(f"kaggle {' '.join(args)} failed:\n{out.strip()}")
    return out


def dataset_exists() -> bool:
    try:
        kaggle("datasets", "status", CKPT_REF, timeout=120)
        return True
    except RuntimeError:
        return False


